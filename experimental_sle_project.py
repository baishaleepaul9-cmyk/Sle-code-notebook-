def fix_excel_gene_names(gene):
    gene = str(gene)

    month_map = {
        "Jan": "JAN",
        "Feb": "FEB",
        "Mar": "MARCH",
        "Apr": "APR",
        "May": "MAY",
        "Jun": "JUN",
        "Jul": "JUL",
        "Aug": "AUG",
        "Sep": "SEPT",
        "Oct": "OCT",
        "Nov": "NOV",
        "Dec": "DEC"
    }

    if "-" in gene:
        parts = gene.split("-")
        if len(parts) == 2:
            num, month = parts
            if month in month_map:
                return month_map[month] + num

    return gene

