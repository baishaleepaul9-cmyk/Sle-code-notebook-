    best_idx = np.argmax(tpr - fpr)
    best_threshold = thresholds[best_idx]

    print("Best ROC threshold:", best_threshold)

    y_pred_tuned = (y_prob >= best_threshold).astype(int)

    print("\nAfter ROC threshold tuning:")
    print("Accuracy:", accuracy_score(y_test, y_pred_tuned))
    print("ROC-AUC:", roc_auc_score(y_test, y_prob))
    print(confusion_matrix(y_test, y_pred_tuned))
    print(classification_report(y_test, y_pred_tuned))

    # Manual thresholds to reduce Healthy -> SLE false positives
    print("\nManual threshold comparison:")

    threshold_results = []

    for threshold in [0.5, 0.6, 0.7, 0.8, 0.9]:
        y_pred_temp = (y_prob >= threshold).astype(int)

        cm = confusion_matrix(y_test, y_pred_temp)
        tn, fp, fn, tp = cm.ravel()

        acc = accuracy_score(y_test, y_pred_temp)
        auc = roc_auc_score(y_test, y_prob)
        sensitivity = tp / (tp + fn)
        specificity = tn / (tn + fp)

        threshold_results.append({
            "Model": name,
            "Threshold": threshold,
            "Accuracy": acc,
            "ROC_AUC": auc,
            "Sensitivity_SLE": sensitivity,
            "Specificity_Healthy": specificity,
            "False_Positive_Healthy_as_SLE": fp,
            "False_Negative_SLE_as_Healthy": fn
        })

