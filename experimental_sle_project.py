import numpy as np
import matplotlib.pyplot as plt
import os

fig_path = "/content/drive/MyDrive/SLE_GEO_Project/SEVERITY_BIOMARKER_INTERPRETATION_FIGURES"

volcano_df = severity_corr_df.copy()
volcano_df["-log10(p-value)"] = -np.log10(volcano_df["P_value"])

volcano_df["Significant"] = (
    (volcano_df["FDR"] < 0.05) &
    (abs(volcano_df["Spearman_r"]) > 0.2)
)

plt.figure(figsize=(9,7))

plt.scatter(
    volcano_df["Spearman_r"],
    volcano_df["-log10(p-value)"],
    alpha=0.5
)

sig_df = volcano_df[volcano_df["Significant"]]

plt.scatter(
    sig_df["Spearman_r"],
    sig_df["-log10(p-value)"],
    alpha=0.9
)

plt.axhline(-np.log10(0.05), linestyle="--")
plt.axvline(0.2, linestyle="--")
plt.axvline(-0.2, linestyle="--")

plt.xlabel("Spearman Correlation with SLEDAI")
plt.ylabel("-log10 P-value")
plt.title("Volcano Plot of Severity-Associated Genes")

plt.tight_layout()

plt.savefig(
    os.path.join(fig_path, "Severity_Genes_Volcano_Plot.png"),
    dpi=300,
    bbox_inches="tight"
)

plt.show()

